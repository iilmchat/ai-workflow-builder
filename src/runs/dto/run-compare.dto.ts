import type { NodeRunStatus } from '../../db/schema.js';
import type { RunSummary } from './run-history.dto.js';

/**
 * Различие одного узла между двумя запусками (v1.4.0 S2, DESIGN V140 § 3.2).
 *
 * Узел присутствует в объединении `node_runs` обоих запусков: если в одном
 * запуске узла не было (он не дошёл до него или граф отличался), его
 * `status`/`duration`/`cost` равны `null`. Это важнее, чем подставлять `0`:
 * «узла не было» и «узел выполнился за 0 мс бесплатно» — разные факты.
 *
 * **Стоимости.** `cost1`/`cost2` — USD (`node_runs.cost_usd`), как и в
 * DESIGN § 3.2 («сравнение по costUsd»). Рублёвые траты media-узлов
 * агрегируются отдельно в `RunCompareTotalDiff.costRub`, чтобы валюты не
 * смешивались (RULES 4.23).
 */
export interface NodeDiff {
  /** `id` узла внутри snapshot (общий для обоих запусков). */
  nodeId: string;
  /** Статус узла в первом запуске; `null` — узла в запуске не было. */
  status1: NodeRunStatus | null;
  /** Статус узла во втором запуске; `null` — узла в запуске не было. */
  status2: NodeRunStatus | null;
  /**
   * Человекочитаемый diff `outputs` (JSON-строка) либо `undefined`, если
   * выходы совпали или узла нет ни в одном запуске.
   *
   * Формат — `{ changed, onlyRun1, onlyRun2 }`: изменённые ключи с обоими
   * значениями и ключи, присутствующие только в одном запуске. Строка
   * обрезается до 100 КБ с пометкой в конце (DESIGN § 7).
   */
  outputsDiff?: string;
  /** Длительность узла в первом запуске, мс; `null` — узла не было/не завершён. */
  duration1: number | null;
  /** Длительность узла во втором запуске, мс; `null` — узла не было/не завершён. */
  duration2: number | null;
  /** Стоимость узла в первом запуске, USD; `null` — узла не было. */
  cost1: number | null;
  /** Стоимость узла во втором запуске, USD; `null` — узла не было. */
  cost2: number | null;
}

/**
 * Суммарная разница между запусками (v1.4.0 S2).
 *
 * Значения — **дельты `run2 − run1`**: положительное число означает, что во
 * втором запуске показатель больше. UI показывает их со знаком и подсвечивает
 * рост красным, снижение — зелёным.
 */
export interface RunCompareTotalDiff {
  /** Разница длительностей, мс; `null`, если длительность хотя бы одного запуска неизвестна. */
  durationMs: number | null;
  /** Разница стоимости в USD (`run2.costUsd − run1.costUsd`). */
  costUsd: number;
  /** Разница стоимости в рублях (`run2.costRub − run1.costRub`). */
  costRub: number;
}

/**
 * Ответ `GET /runs/:id1/compare/:id2` (v1.4.0 S2, DESIGN V140 § 3.2).
 *
 * `run1`/`run2` — та же лёгкая проекция, что у истории запусков
 * ({@link RunSummary}): статус, даты, длительность и суммы по валютам. Курсор
 * keyset-пагинации в ответе формально присутствует (общий DTO), но для
 * сравнения не используется — это цена переиспользования проекции, а не
 * отдельного DTO-дубля.
 */
export interface RunCompareResponse {
  /** Первый запуск (левый столбец UI). */
  run1: RunSummary;
  /** Второй запуск (правый столбец UI). */
  run2: RunSummary;
  /** Поузловые различия и суммарные дельты. */
  diffs: {
    /** Различия по каждому узлу объединения, отсортированы по `nodeId`. */
    nodeDiffs: NodeDiff[];
    /** Дельты итоговых показателей (`run2 − run1`). */
    totalDiff: RunCompareTotalDiff;
  };
}

/**
 * Максимальный размер одной строки `outputsDiff` — 100 КБ (DESIGN § 7).
 *
 * Ограничение защищает UI и SSE/REST-ответ от мегабайтных outputs
 * (LLM-промпты, документы, base64): diff обрезается с явной пометкой в конце,
 * поэтому пользователь видит, что часть данных не показана.
 */
export const MAX_COMPARE_DIFF_BYTES = 100 * 1024;
