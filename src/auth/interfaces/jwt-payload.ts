/**
 * Полезная нагрузка access-токена.
 *
 * `sub` — id пользователя (uuid) по RFC 7519. Refresh-токена нет: MVP R6.1a
 * выдаёт только access на 24 часа (упрощение зафиксировано в отчёте).
 *
 * `orgId` — организация-арендатор (DESIGN_V100_ENTERPRISE § 3.1): guard
 * сверяет её с `users.organization_id` и кладёт актуальное значение в
 * `request.user` (v1.1.0 S5). Поле обязательно, поэтому старые JWT без
 * `orgId` инвалидируются (DESIGN § 4) — после миграции на organizations клиент
 * обязан войти заново.
 *
 * `ver` — версия access-токена (`users.token_version`, v1.1.0 S5, KI-601).
 * Увеличивается при принудительном отзыве сессий; `JwtAuthGuard` сверяет
 * значение с БД. Токены, выпущенные до S5, поля не содержат — они считаются
 * версией 0 (DEFAULT колонки), то есть остаются валидными, пока версия не
 * изменится; несовпадение `orgId` при этом всё равно даёт 401.
 */
export interface JwtPayload {
  /** id пользователя (uuid). */
  sub: string;
  /** Email пользователя — для UI и логов без второго запроса в БД. */
  email: string;
  /** id организации-арендатора (uuid, DESIGN § 3.1). */
  orgId: string;
  /** Версия access-токена (`users.token_version`, v1.1.0 S5). */
  ver: number;
}
