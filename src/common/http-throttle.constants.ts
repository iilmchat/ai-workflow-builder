/**
 * Лимиты HTTP rate limiting (KI-206, KI-234).
 *
 * Общий лимит (`default`) — «предохранитель от флуда» на каждый маршрут: его
 * хватает обычному UI (поллинг бюджета, автосохранение), но он не защищает от
 * целенаправленного брутфорса. Для чувствительных ручек лимит ужесточается
 * точечно декоратором `@Throttle` (см. {@link LOGIN_THROTTLE},
 * {@link SHARE_THROTTLE}).
 *
 * Значения статические: `@Throttle` вычисляется на этапе объявления класса и не
 * может читать `ConfigService`. Если лимиты понадобится менять из окружения,
 * это делается через `ThrottlerModule.forRootAsync` (KI-422).
 */

/** Окно подсчёта запросов (мс): одна минута. */
export const HTTP_THROTTLE_TTL_MS = 60_000;

/**
 * Числовой лимит для `@Throttle`.
 *
 * Отдельный тип, а не `ThrottlerOptions`: там `limit`/`ttl` —
 * `Resolvable<number>` (могут быть функциями), а тестам и документации нужны
 * конкретные числа.
 */
export interface HttpThrottleLimit {
  /** Максимум запросов за окно. */
  readonly limit: number;
  /** Окно подсчёта, мс. */
  readonly ttl: number;
}

/**
 * Общий лимит запросов на маршрут за окно.
 *
 * 300/мин (5 req/s) — с большим запасом для UI; строгие лимиты задаются
 * отдельно. Глобальный guard включён именно с этим лимитом, чтобы новые
 * публичные ручки не оставались без ограничения по умолчанию.
 */
export const HTTP_THROTTLE_DEFAULT_LIMIT = 300;

/**
 * Строгий лимит `POST /auth/login` — 5 попыток в минуту с одного IP.
 *
 * Защита от брутфорса пароля (KI-206): успешные и неуспешные попытки считаются
 * одинаково, поэтому перебор быстро упирается в 429.
 */
export const LOGIN_THROTTLE: HttpThrottleLimit = {
  limit: 5,
  ttl: HTTP_THROTTLE_TTL_MS,
};

/**
 * Строгий лимит `GET /workflow/share/:token` — 5 запросов в минуту с одного IP.
 *
 * Публичная ручка без аутентификации: перебор uuid v4 нереален, но
 * сканирование/DoS иначе ничем не ограничены (KI-234).
 */
export const SHARE_THROTTLE: HttpThrottleLimit = {
  limit: 5,
  ttl: HTTP_THROTTLE_TTL_MS,
};
