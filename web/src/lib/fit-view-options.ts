/**
 * Единые опции подгонки вида для всех fit-операций (KI-306/310/311).
 *
 * Источник правды один, потому что fit-операций несколько, и они легко
 * расходятся:
 * - `useEffect` после загрузки графа (F5) — `web/src/components/Canvas.tsx`;
 * - хоткей `F` — там же;
 * - кнопка Fit из `<Controls fitViewOptions>` — там же;
 * - `<ReactFlow fitViewOptions>` как дефолт — там же;
 * - fit по выделению (`Shift+F` и кнопка «Вписать выделение») — там же;
 * - публичная share-страница — `web/src/components/ShareViewPage.tsx` (KI-310).
 *
 * `minZoom` живёт **в опциях fitView**, а не в `<ReactFlow minZoom>`:
 * `getViewportForBounds` (@xyflow/system) читает `options.minZoom` приоритетно
 * перед store-значением, поэтому fit умещает граф с большим разбросом
 * (например, `Y = −21888` после накопленного `autoPanOnNodeDrag`, KI-307),
 * а пользовательский зум колесом остаётся ограничен store-значением `0.5`.
 *
 * `maxZoom: 1` — без него один-два узла растягиваются на весь экран.
 * `as const` фиксирует литеральные типы: опечатка в имени/значении или
 * `minZoom > maxZoom` видны на уровне типов и в тестах.
 */

/**
 * Опции fit по всему графу (F5, хоткей `F`, кнопка Fit, `<Controls>`).
 *
 * `minZoom: 0.005` (KI-314) — предел читается как «сколько пикселей разброса
 * умещается в кадр»: при вьюпорте 1600×656 это ≈ 320 000 × 131 200 px модели,
 * то есть с запасом покрывает наблюдавшиеся 21 888 px и расчётные 50 000 px.
 * Прежнее значение `0.02` умещало только ≈ 23 050 px по вертикали (KI-314),
 * после чего узлы уходили за кадр.
 *
 * Осознанный компромисс: на разбросе в тысячи пикселей узлы физически не могут
 * быть читаемыми (KI-328) — для этого существует {@link FIT_SELECTION_OPTIONS}.
 */
export const FIT_VIEW_OPTIONS = {
  padding: 0.2,
  maxZoom: 1,
  minZoom: 0.005,
} as const;

/**
 * Опции fit по выделенным узлам (KI-328): «в кадре» ≠ «читаемо».
 *
 * Fit по всему bbox усредняет масштаб по крайним узлам: при разбросе
 * 21 888 px карточки превращались в 4–6 px (KI-328). Поэтому у выделения
 * отдельный набор с `minZoom: 0.1` — нижняя граница читаемости: даже если
 * выделенные узлы не уместились целиком, масштаб остаётся осмысленным, а
 * остальное доступно панорамированием.
 *
 * `padding: 0.3` больше, чем у {@link FIT_VIEW_OPTIONS}: в кадре обычно 2–5
 * узлов, и запас по краям помогает увидеть их связи и подписи. `maxZoom: 1`
 * сохраняет то же ограничение «не растягивать один узел на весь экран».
 *
 * Инвариант `FIT_SELECTION_OPTIONS.minZoom > FIT_VIEW_OPTIONS.minZoom` закреплён
 * тестом: fit по выделению обязан быть строго «ближе», чем fit по всему графу.
 */
export const FIT_SELECTION_OPTIONS = {
  padding: 0.3,
  maxZoom: 1,
  minZoom: 0.1,
} as const;
