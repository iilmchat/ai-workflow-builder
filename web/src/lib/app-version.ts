import { version } from '../../package.json';

/**
 * Версия продукта для интерфейса (RULES 1.11, KI-446).
 *
 * Источник — `web/package.json`: версия не дублируется руками ни в разметке, ни
 * в env. Импортируется **именованное** поле, а не весь JSON: Vite превращает
 * `package.json` в ES-модуль с экспортом на каждый ключ, и tree-shaking
 * оставляет в бандле только `version` (с импортом по умолчанию в клиент
 * попадали бы `devDependencies` и прочие служебные поля).
 *
 * Явная аннотация `string` важна: `resolveJsonModule` выводит литеральный тип
 * (`"0.9.1"`), и любая правка разметки, ожидающей число, прошла бы незаметно.
 */
export const APP_VERSION: string = version;

/**
 * Год копирайта (RULES 1.12).
 *
 * Отдельная константа, а не `new Date().getFullYear()`: год в копирайте — факт
 * релиза, а не текущая дата пользователя. Иначе тест «версия и копирайт на
 * месте» ломался бы 1 января.
 */
export const APP_COPYRIGHT_YEAR = '2026';
